"""Writing `models.py`: one Pydantic class per object schema and a plain alias for any other component schema."""

from .schema import AliasDef, FieldDef, ModelDef
from .writer import WIDTH, CodeWriter, import_lines, quote, string_expr

HEADER = "# Generated by tools.openapi_codegen from {source}. Do not edit; regenerate instead."

_STDLIB_IMPORTS = {"datetime": "datetime", "date": "datetime", "time": "datetime", "UUID": "uuid"}
_TYPING_IMPORTS = {"Annotated", "Any", "Literal"}


def stdlib_import_lines(symbols: set[str]) -> list[str]:
    """The `from ... import ...` lines (sorted by module) for the stdlib symbols a generated file uses."""
    by_module: dict[str, set[str]] = {}
    for symbol in symbols:
        if symbol in _STDLIB_IMPORTS:
            by_module.setdefault(_STDLIB_IMPORTS[symbol], set()).add(symbol)
        elif symbol in _TYPING_IMPORTS:
            by_module.setdefault("typing", set()).add(symbol)
    lines: list[str] = []
    for module in sorted(by_module):
        lines.extend(import_lines(module, by_module[module]))
    return lines


def render_models(models: dict[str, ModelDef], aliases: dict[str, AliasDef], source: str) -> str:
    order = _dependency_order(models, aliases)
    position = {name: index for index, name in enumerate(order)}

    symbols: set[str] = set()
    pydantic: set[str] = set()
    for name in order:
        if name in models:
            symbols |= models[name].imports
            if not models[name].bases:
                pydantic.add("BaseModel")
            if _model_config(models[name]):
                pydantic.add("ConfigDict")
            if any(_needs_field(f) for f in models[name].fields):
                pydantic.add("Field")
        else:
            symbols |= aliases[name].type.imports
    if "Field" in symbols:
        pydantic.add("Field")

    w = CodeWriter()
    w.line(HEADER.format(source=source))
    w.line('"""The data classes of the API: its request and response objects."""')
    w.blank()
    w.line("from __future__ import annotations")
    w.blank()
    for line in stdlib_import_lines(symbols):
        w.line(line)
    if pydantic:
        w.blank()
        for line in import_lines("pydantic", pydantic):
            w.line(line)

    rebuild: list[str] = []
    for name in order:
        w.blank(2)
        if name in models:
            _render_model(w, models[name])
            if any(position.get(dep, -1) >= position[name] for dep in models[name].deps):
                rebuild.append(name)
        else:
            alias = aliases[name]
            w.line(f"{name} = {alias.type.expr}")
            if alias.description:
                w.docstring(alias.description)
    if rebuild:
        w.blank(2)
        w.line("# These refer to classes defined after them (or to themselves).")
        for name in rebuild:
            w.line(f"{name}.model_rebuild()")
    return w.getvalue()


def _needs_field(item: FieldDef) -> bool:
    return item.aliased or bool(item.description)


def _model_config(model: ModelDef) -> list[str]:
    options = []
    if any(f.aliased for f in model.fields):
        options.append("populate_by_name=True")
    if model.extra:
        options.append(f"extra={quote(model.extra)}")
    return options


def _render_model(w: CodeWriter, model: ModelDef) -> None:
    bases = ", ".join(model.bases) or "BaseModel"
    with w.block(f"class {model.name}({bases}):"):
        wrote = False
        if model.description:
            w.docstring(model.description)
            wrote = True
        options = _model_config(model)
        if options:
            if wrote:
                w.blank()
            w.line(f"model_config = ConfigDict({', '.join(options)})")
            wrote = True
        if model.fields and wrote:
            w.blank()
        for item in model.fields:
            render_field(w, item)
            wrote = True
        if not wrote:
            w.line("pass")


def render_field(w: CodeWriter, item: FieldDef) -> None:
    annotation = f"{item.name}: {item.type.expr}"
    default = item.default if item.default is not None else None if item.required else "None"
    if not _needs_field(item):
        w.line(annotation if default is None else f"{annotation} = {default}")
        return
    arguments = []
    if default is not None:
        arguments.append(f"default={default}")
    if item.aliased:
        arguments.append(f"alias={quote(item.wire)}")
    flat = [*arguments, *([f"description={quote(item.description)}"] if item.description else [])]
    one_line = f"{annotation} = Field({', '.join(flat)})"
    if w.column + len(one_line) <= WIDTH:
        w.line(one_line)
        return
    w.line(f"{annotation} = Field(")
    pad = w.column + 4
    for argument in arguments:
        w.raw(" " * pad + argument + ",")
    if item.description:
        text = string_expr(item.description, pad, pad + len("description="))
        w.raw(" " * pad + "description=" + text + ",")
    w.line(")")


def _dependency_order(models: dict[str, ModelDef], aliases: dict[str, AliasDef]) -> list[str]:
    """Definitions before the ones that use them; a cycle is cut where it is found (see `model_rebuild`)."""
    deps = {name: model.deps for name, model in models.items()} | {name: a.type.deps for name, a in aliases.items()}
    ordered: list[str] = []
    state: dict[str, int] = {}

    def ancestors(name: str) -> set[str]:
        found: set[str] = set()
        for base in models[name].bases if name in models else ():
            found |= {base} | ancestors(base)
        return found

    def visit(name: str) -> None:
        if state.get(name):
            return
        state[name] = 1
        bases = models[name].bases if name in models else []
        for dep in sorted(deps[name], key=lambda d: d not in bases):
            if dep not in deps:
                continue
            # A field may refer to a subclass of a model still being defined; that one has to wait for it.
            if dep not in bases and any(state.get(a) == 1 for a in ancestors(dep)):
                continue
            visit(dep)
        ordered.append(name)

    for name in sorted(deps):
        visit(name)
    return ordered
