"""Turns an OpenAPI document into the files of a Python package: models, clients and Flask blueprints."""

import json
import re
from pathlib import Path
from typing import Any

from .emit_blueprint import render_blueprint, render_blueprints_init
from .emit_client import render_client
from .emit_models import HEADER, render_models
from .operations import Operations, Route
from .schema import Schemas, SpecError
from .writer import CodeWriter, import_lines

MARKER = "# Generated by tools.openapi_codegen"
_RUNTIME = Path(__file__).parent / "runtime"


def generate(document: dict[str, Any], source: str = "openapi.json") -> dict[str, str]:
    """The generated package as `{relative path: source text}`."""
    version = str(document.get("openapi", ""))
    if not version.startswith("3."):
        raise SpecError(f"only OpenAPI 3.x documents are supported (this one says {version or 'nothing'!r})")

    schemas = Schemas(document)
    routes = Operations(schemas).routes()
    models, aliases = schemas.finish()
    model_names = set(models) | set(aliases)

    files = {
        "__init__.py": f"{HEADER.format(source=source)}\n{_package_docstring(document)}\n",
        "models.py": render_models(models, aliases, source),
        "clients/__init__.py": _render_clients_init(routes, source),
        "clients/_base.py": (_RUNTIME / "client_base.py").read_text(),
        "blueprints/__init__.py": render_blueprints_init(routes, source),
        "blueprints/_base.py": (_RUNTIME / "blueprint_base.py").read_text(),
    }
    for route in routes:
        files[f"clients/{route.module}.py"] = render_client(route, model_names, source)
        files[f"blueprints/{route.module}.py"] = render_blueprint(route, model_names, source)
    return files


def write_files(files: dict[str, str], out: Path) -> list[str]:
    """Writes `files` under `out`, removing generated files from an earlier run that are no longer produced.
    Returns the relative paths removed."""
    removed = []
    for existing in sorted(out.rglob("*.py")) if out.exists() else []:
        relative = existing.relative_to(out).as_posix()
        if relative not in files and existing.read_text().startswith(MARKER):
            existing.unlink()
            removed.append(relative)
    for relative, text in files.items():
        target = out / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return removed


def stale_files(files: dict[str, str], out: Path) -> list[str]:
    """The paths under `out` that differ from what `files` would write (missing, changed or left over)."""
    stale = [
        relative
        for relative, text in files.items()
        if not (out / relative).exists() or (out / relative).read_text() != text
    ]
    for existing in sorted(out.rglob("*.py")) if out.exists() else []:
        relative = existing.relative_to(out).as_posix()
        if relative not in files and existing.read_text().startswith(MARKER):
            stale.append(relative)
    return stale


_YAML_SUFFIXES = {".yaml", ".yml"}


def load(path: Path) -> dict[str, Any]:
    """Reads an OpenAPI document: YAML if the file is named .yaml or .yml (which needs PyYAML), otherwise JSON."""
    text = path.read_text()
    if path.suffix.lower() in _YAML_SUFFIXES:
        return _load_yaml(path, text)
    try:
        return json.loads(text)
    except json.JSONDecodeError as error:
        raise SpecError(f"{path} isn't valid JSON: {error}") from error


def _load_yaml(path: Path, text: str) -> dict[str, Any]:
    """PyYAML is only imported here, so JSON users need nothing beyond the standard library.

    It reads YAML 1.1, which would turn several things in a spec into something JSON can't say, so the loader
    is narrowed to what JSON would have meant: only true and false are booleans (not yes, no, on, off, which
    would otherwise corrupt an enum), dates stay strings, and a repeated key is an error rather than the last
    one silently winning. An unquoted integer key, as in `200:`, is a status code and becomes "200"."""
    try:
        import yaml
    except ImportError as error:
        raise SpecError(
            f"{path} is YAML, which needs PyYAML (pip install pyyaml); a JSON spec needs nothing extra"
        ) from error

    timestamp, boolean = "tag:yaml.org,2002:timestamp", "tag:yaml.org,2002:bool"
    true_or_false = re.compile(r"^(?:true|false|True|False|TRUE|FALSE)$")
    resolvers: dict[str, list] = {}
    for first_char, entries in yaml.SafeLoader.yaml_implicit_resolvers.items():
        kept = []
        for tag, pattern in entries:
            if tag == timestamp or (tag == boolean and first_char not in "tTfF"):
                continue
            kept.append((tag, true_or_false if tag == boolean else pattern))
        if kept:
            resolvers[first_char] = kept

    class Loader(yaml.SafeLoader):
        yaml_implicit_resolvers = resolvers

        def construct_mapping(self, node, deep=False):
            seen = set()
            for key_node, _ in node.value:
                if key_node.tag == "tag:yaml.org,2002:merge":
                    continue
                key = self.construct_object(key_node, deep=True)
                if key in seen:
                    raise SpecError(f"{path}, line {key_node.start_mark.line + 1}: the key {key!r} appears twice")
                seen.add(key)
            return super().construct_mapping(node, deep)

    try:
        document = yaml.load(text, Loader=Loader)
    except yaml.YAMLError as error:
        raise SpecError(f"{path} isn't valid YAML: {error}") from error
    return _string_keys(document, path)


def _string_keys(node: Any, path: Path) -> Any:
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if isinstance(key, int) and not isinstance(key, bool):
                key = str(key)
            elif not isinstance(key, str):
                raise SpecError(f"{path}: the key {key!r} isn't a string; quote it")
            out[key] = _string_keys(value, path)
        return out
    if isinstance(node, list):
        return [_string_keys(item, path) for item in node]
    return node


def _package_docstring(document: dict[str, Any]) -> str:
    title = str(document.get("info", {}).get("title", "")) or "API"
    return f'"""Generated from the {title} OpenAPI document."""'


def _render_clients_init(routes: list[Route], source: str) -> str:
    w = CodeWriter()
    w.line(HEADER.format(source=source))
    w.line('"""Clients, one module per route."""')
    w.blank()
    w.line("from __future__ import annotations")
    w.blank()
    for line in import_lines("._base", ["ApiError", "BaseClient"]):
        w.line(line)
    names = ["ApiError", "BaseClient"]
    for route in sorted(routes, key=lambda r: r.module):
        client = f"{route.prefix}Client"
        names.append(client)
        for line in import_lines(f".{route.module}", [client]):
            w.line(line)
    w.blank()
    w.line("__all__ = [")
    for name in sorted(names):
        w.line(f'    "{name}",')
    w.line("]")
    return w.getvalue()
